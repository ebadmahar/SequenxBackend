def seed_site_assets(db: Session) -> None:
    """Pre-seed all registered site assets if not already present."""
    for asset_data in DEFAULT_SITE_ASSETS:
        existing = db.query(SiteAsset).filter(SiteAsset.key == asset_data["key"]).first()
        if not existing:
            asset = SiteAsset(
                key=asset_data["key"],
                page=asset_data["page"],
                location_keyword=asset_data["location_keyword"],
                asset_type=asset_data["asset_type"],
                aspect_ratio=asset_data["aspect_ratio"],
                dimensions=asset_data["dimensions"],
                current_url=None, # Initially uses fallback_url
                fallback_url=asset_data["fallback_url"],
                alt_text=asset_data["alt_text"],
            )
            db.add(asset)
    db.commit()

